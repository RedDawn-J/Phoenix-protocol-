#!/usr/bin/env python3
"""Generate and validate small Sovereign Shards starter products from JSON specs."""
from __future__ import annotations

import argparse
import ast
import html
import json
import re
import sys
from html.parser import HTMLParser
from pathlib import Path
from typing import Any

from scripts.shardsc import ShardError, compile_source

SLUG_PATTERN = re.compile(r"^[a-z][a-z0-9-]{0,47}$")
SUPPORTED_KINDS = {"website", "python-cli", "shards-app"}


class ProductError(ValueError):
    """Invalid product specification or generation failure."""


class HtmlValidator(HTMLParser):
    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.errors: list[str] = []
        self.stack: list[str] = []
        self.void_tags = {"area", "base", "br", "col", "embed", "hr", "img", "input", "link", "meta", "param", "source", "track", "wbr"}

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        if tag not in self.void_tags:
            self.stack.append(tag)

    def handle_endtag(self, tag: str) -> None:
        if tag in self.void_tags:
            return
        if not self.stack or self.stack[-1] != tag:
            self.errors.append(f"unexpected closing tag </{tag}>")
            return
        self.stack.pop()

    def finish(self) -> list[str]:
        if self.stack:
            self.errors.append("unclosed tags: " + ", ".join(self.stack))
        return self.errors


def load_spec(path: Path) -> dict[str, Any]:
    try:
        spec = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise ProductError(f"cannot load JSON product spec {path}: {exc}") from exc
    if not isinstance(spec, dict):
        raise ProductError("product spec root must be a JSON object")
    return spec


def validate_spec(spec: dict[str, Any]) -> None:
    name = spec.get("name")
    kind = spec.get("kind")
    title = spec.get("title", name)
    description = spec.get("description", "")
    if not isinstance(name, str) or not SLUG_PATTERN.fullmatch(name):
        raise ProductError("name must be a lowercase project slug (letters, digits, hyphens; start with a letter)")
    if kind not in SUPPORTED_KINDS:
        raise ProductError(f"kind must be one of: {', '.join(sorted(SUPPORTED_KINDS))}")
    if not isinstance(title, str) or not title.strip() or len(title) > 160:
        raise ProductError("title must contain 1 to 160 characters")
    if not isinstance(description, str) or len(description) > 2_000:
        raise ProductError("description must be text no longer than 2,000 characters")
    if kind == "shards-app":
        source = spec.get("source")
        if not isinstance(source, str) or not source.strip():
            raise ProductError("shards-app specs require non-empty source")
        compile_source(source)
    if kind == "python-cli" and spec.get("source"):
        try:
            ast.parse(spec["source"])
        except (SyntaxError, TypeError) as exc:
            raise ProductError(f"python source does not parse: {exc}") from exc


def render_website(spec: dict[str, Any]) -> str:
    title = html.escape(spec.get("title", spec["name"]))
    description = html.escape(spec.get("description", ""))
    heading = html.escape(spec.get("heading", title))
    body = html.escape(spec.get("body", description)).replace("\n", "<br>\n")
    return f'''<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="description" content="{description}">
  <title>{title}</title>
  <style>
    :root {{ color-scheme: light; font-family: system-ui, sans-serif; color: #242424; background: #f7f5f0; }}
    body {{ margin: 0; min-height: 100vh; display: grid; place-items: center; }}
    main {{ max-width: 760px; padding: 3rem 2rem; }}
    h1 {{ font-size: clamp(2.5rem, 8vw, 5rem); line-height: 1.05; letter-spacing: -.04em; }}
    p {{ color: #555; line-height: 1.7; font-size: 1.1rem; }}
  </style>
</head>
<body>
  <main>
    <h1>{heading}</h1>
    <p>{body}</p>
  </main>
</body>
</html>
'''


def render_python(spec: dict[str, Any]) -> str:
    source = spec.get("source")
    if isinstance(source, str) and source.strip():
        return source.rstrip() + "\n"
    message = json.dumps(spec.get("description", "Hello from J-Forge"), ensure_ascii=False)
    return (
        "\"\"\"Generated command-line application.\"\"\"\n\n"
        "import argparse\n\n\n"
        "def main() -> int:\n"
        "    parser = argparse.ArgumentParser(description=\"Generated by J-Forge\")\n"
        "    parser.add_argument(\"--name\", default=\"world\")\n"
        "    args = parser.parse_args()\n"
        f"    print({message} + f\", {{args.name}}!\")\n"
        "    return 0\n\n\n"
        "if __name__ == \"__main__\":\n"
        "    raise SystemExit(main())\n"
    )


def render_shards(spec: dict[str, Any]) -> str:
    source = spec["source"].rstrip()
    return source + "\n"


def product_files(spec: dict[str, Any]) -> dict[str, str]:
    validate_spec(spec)
    readme = (
        f"# {spec.get('title', spec['name'])}\n\n"
        f"{spec.get('description', 'Generated starter product.')}\n\n"
        "## Generated by J-Forge\n\n"
        f"Product kind: `{spec['kind']}`. See `docs/J_FORGE.md` for the builder and language workflow.\n"
    )
    if spec["kind"] == "website":
        return {"index.html": render_website(spec), "README.md": readme}
    if spec["kind"] == "python-cli":
        source = render_python(spec)
        try:
            ast.parse(source)
        except SyntaxError as exc:
            raise ProductError(f"generated Python failed syntax validation: {exc}") from exc
        return {"main.py": source, "README.md": readme}
    source = render_shards(spec)
    compile_source(source)
    return {"main.shard": source, "README.md": readme}


def validate_generated(files: dict[str, str]) -> list[str]:
    failures: list[str] = []
    for path, content in files.items():
        if path.endswith(".py"):
            try:
                ast.parse(content)
            except SyntaxError as exc:
                failures.append(f"{path}: {exc}")
        elif path.endswith(".shard"):
            try:
                compile_source(content)
            except ShardError as exc:
                failures.append(f"{path}: {exc}")
        elif path.endswith(".html"):
            validator = HtmlValidator()
            try:
                validator.feed(content)
                validator.close()
            except Exception as exc:
                failures.append(f"{path}: HTML parser error: {exc}")
            failures.extend(f"{path}: {error}" for error in validator.finish())
    return failures


def write_product(files: dict[str, str], output: Path, overwrite: bool) -> list[Path]:
    output.mkdir(parents=True, exist_ok=True)
    created: list[Path] = []
    for relative_path, content in files.items():
        target = (output / relative_path).resolve()
        try:
            target.relative_to(output.resolve())
        except ValueError as exc:
            raise ProductError("generated output escapes the selected destination") from exc
        if target.exists() and not overwrite:
            raise ProductError(f"refusing to overwrite {target}; pass --overwrite to replace generated files")
        target.parent.mkdir(parents=True, exist_ok=True)
        temporary = target.with_suffix(target.suffix + ".tmp")
        temporary.write_text(content, encoding="utf-8")
        temporary.replace(target)
        created.append(target)
    return created


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate and validate a starter product from a J-Forge JSON spec.")
    parser.add_argument("spec", type=Path, help="JSON product specification")
    parser.add_argument("--output", type=Path, default=Path.cwd(), help="output directory")
    parser.add_argument("--overwrite", action="store_true", help="replace generated files that already exist")
    args = parser.parse_args(argv)
    try:
        spec = load_spec(args.spec)
        files = product_files(spec)
        failures = validate_generated(files)
        if failures:
            raise ProductError("generated artifact validation failed: " + "; ".join(failures))
        created = write_product(files, args.output, args.overwrite)
        for path in created:
            print(f"OK · wrote {path}")
        print(f"OK · falsification gate passed: {len(files)} generated artifact(s) validated")
        return 0
    except (OSError, ProductError) as exc:
        print(f"FAIL · {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
